#!/usr/bin/env python3
"""scripts/amalgamate-golden.py — one self-contained C++ file for a Compiler Explorer cross-check (FR-H4, 2.1.7).

Inlines every `#include <es/serreg/...>` / `#include <es/ipc/...>` and `#include "corpus.hpp"` reachable from
tests/golden/hashes.cpp (each file once, in include order), defines ES_SERREG_GOLDEN_STANDALONE and writes the
result to stdout. Paste it into https://godbolt.org/ with
    x86-64 gcc 16                    -std=c++26 -freflection -fsyntax-only
    x86-64 clang (experimental P2996) -std=c++26 -freflection-latest -stdlib=libc++ -fsyntax-only
Both must compile it: every frozen hash, canonical string, field table and frame size is a static_assert.

usage: scripts/amalgamate-golden.py [> golden-ce.cpp]      (standard library only)
"""
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INC = re.compile(r'^\s*#\s*include\s*([<"])([^>"]+)[>"]')
seen = set()
out = []


def resolve(name, quote, here):
    if quote == "<" and (name.startswith("es/serreg/") or name.startswith("es/ipc/")):
        return os.path.join(REPO, "include", name)
    if quote == '"':
        for base in (here, os.path.join(REPO, "tests", "golden")):
            p = os.path.join(base, name)
            if os.path.exists(p):
                return p
    return None


def emit(path):
    path = os.path.normpath(path)
    if path in seen:
        return
    seen.add(path)
    rel = os.path.relpath(path, REPO)
    out.append(f"// ===== {rel} =====")
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            if line.strip() == "#pragma once":
                continue
            m = INC.match(line)
            if m:
                target = resolve(m.group(2), m.group(1), os.path.dirname(path))
                if target:
                    emit(target)
                    continue
            out.append(line.rstrip("\n"))


def main():
    out.append("// Generated by scripts/amalgamate-golden.py from the es::serreg sources — do not edit.")
    out.append("#define ES_SERREG_GOLDEN_STANDALONE 1")
    emit(os.path.join(REPO, "tests", "golden", "hashes.cpp"))
    sys.stdout.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
