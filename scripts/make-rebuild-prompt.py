#!/usr/bin/env python3
"""make-rebuild-prompt.py — assembles ser-reg-rebuild-v<version>.md, the one file from which the library can be
built again (DECISIONS D-2; docs/ser-reg-rebuild-prompt.md says what goes in and why).

    scripts/make-rebuild-prompt.py [--out DIR] [--quiet]

Writes DIR/ser-reg-rebuild-v<version>.md (DIR defaults to the parent of the repository, next to the release
tarballs) and prints its path, line count and sha256. Exit 1 when a part is missing or the versions disagree.
"""
from __future__ import annotations

import argparse
import hashlib
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

DOCS = [
    "docs/DECISIONS.md",
    "docs/ser-reg-requirements.md",
    "docs/ser-reg-architecture.md",
    "docs/ser-reg-testing.md",
    "docs/ser-reg-stories.md",
]
SOURCES = [  # (path, fence language)
    ("include/es/serreg/format.hpp", "cpp"),
    ("tests/golden/corpus.hpp", "cpp"),
    ("tests/golden/hashes.cpp", "cpp"),
    ("tests/golden/blobs.cpp", "cpp"),
    ("python/serreg/format.py", "python"),
    ("CMakePresets.json", "json"),
    ("cmake/warnings.cmake", "cmake"),
    ("public-files-list.txt", "text"),
]
CHECKSUM_DIRS = ["tests/fixtures"]
CHECKSUM_FILES = [f"ce-examples/ce-example{n}/main.cpp" for n in range(1, 6)]


def read(path: str) -> str:
    with open(os.path.join(REPO, path), encoding="utf-8") as f:
        return f.read()


def version() -> str:
    m = re.search(r"^project\(serreg VERSION ([0-9.]+)", read("CMakeLists.txt"), re.M)
    if not m:
        sys.exit("make-rebuild-prompt: no project(serreg VERSION …) in CMakeLists.txt")
    return m.group(1)


def format_minor() -> str:
    m = re.search(r"format_minor = (\d+);", read("include/es/serreg/format.hpp"))
    return f"1.{m.group(1)}" if m else "?"


def decisions_version() -> str:
    m = re.search(r"\*\*Refers to:\*\* library \*\*([0-9.]+)\*\*", read("docs/DECISIONS.md"))
    return m.group(1) if m else "?"


def leading_comment(path: str) -> str:
    """The block of // comment lines at the top of a header (after a blank first line if any)."""
    out = []
    for line in read(path).splitlines():
        if line.startswith("//"):
            out.append(line)
        elif line.strip() == "" and not out:
            continue
        else:
            break
    return "\n".join(out)


def sha256_of(path: str) -> tuple[str, int]:
    h = hashlib.sha256()
    n = 0
    with open(os.path.join(REPO, path), "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
            n += len(chunk)
    return h.hexdigest(), n


def fence(lang: str, text: str) -> str:
    # a fence longer than any run of backticks inside the text
    longest = max((len(m) for m in re.findall(r"`+", text)), default=0)
    ticks = "`" * max(3, longest + 1)
    return f"{ticks}{lang}\n{text.rstrip()}\n{ticks}\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.dirname(REPO))
    ap.add_argument("--quiet", action="store_true")
    a = ap.parse_args()

    ver = version()
    dv = decisions_version()
    if dv != ver:
        sys.exit(f"make-rebuild-prompt: CMakeLists.txt is {ver} but docs/DECISIONS.md refers to {dv}")
    missing = [p for p in DOCS + [p for p, _ in SOURCES] if not os.path.exists(os.path.join(REPO, p))]
    if missing:
        sys.exit("make-rebuild-prompt: missing " + ", ".join(missing))

    fmt = format_minor()
    core = read("docs/ser-reg-rebuild-prompt.md").replace("<version>", ver).replace("<format>", fmt)
    parts = [
        f"# ser-reg rebuild prompt — library {ver}, wire format {fmt}\n",
        "This file was generated by scripts/make-rebuild-prompt.py from the ser-reg tree; it is self-contained. "
        "Part 1 is the prompt; the parts after it are the documents, the normative sources, the headers' leading "
        "comments and the checksums it refers to.\n",
        "\n---\n\n# Part 1 — the prompt\n\n" + core,
    ]
    for i, doc in enumerate(DOCS, start=2):
        parts.append(f"\n---\n\n# Part {i} — {doc}\n\n" + read(doc))
    n = len(DOCS) + 2
    parts.append(f"\n---\n\n# Part {n} — normative sources\n")
    for path, lang in SOURCES:
        parts.append(f"\n## {path}\n\n" + fence(lang, read(path)))
    n += 1
    parts.append(f"\n---\n\n# Part {n} — the public headers' leading comments\n")
    headers = sorted(
        os.path.join(d, f)
        for d in ("include/es/serreg", "include/es/serreg/detail", "include/es/ipc")
        if os.path.isdir(os.path.join(REPO, d))
        for f in os.listdir(os.path.join(REPO, d))
        if f.endswith(".hpp")
    )
    for h in headers:
        c = leading_comment(h)
        if c:
            parts.append(f"\n## {h}\n\n" + fence("cpp", c))
    n += 1
    parts.append(f"\n---\n\n# Part {n} — checksums (SHA-256, size in bytes)\n\n")
    parts.append("The rebuilt tree must reproduce these files exactly (the fixtures are what the golden tests compare "
                 "against; the ce-examples are the compiler cross-check).\n\n| file | sha256 | bytes |\n|---|---|---|\n")
    files = []
    for d in CHECKSUM_DIRS:
        for root, _, names in os.walk(os.path.join(REPO, d)):
            for name in names:
                files.append(os.path.relpath(os.path.join(root, name), REPO))
    files = sorted(files) + CHECKSUM_FILES
    for f in files:
        digest, size = sha256_of(f)
        parts.append(f"| `{f}` | `{digest}` | {size} |\n")

    text = "".join(parts)
    os.makedirs(a.out, exist_ok=True)
    out = os.path.join(a.out, f"ser-reg-rebuild-v{ver}.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write(text)
    if not a.quiet:
        print(f"{out}: {text.count(chr(10))} lines, sha256 {hashlib.sha256(text.encode()).hexdigest()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
